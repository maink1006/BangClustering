import matplotlib.colors as mcolors
from collections import deque
from sklearn.metrics import silhouette_score

class SpatialBlock:
    def __init__(self, lower, upper, volume_floor=1e-12):
        lower = np.asarray(lower, dtype=float)
        upper = np.asarray(upper, dtype=float)
        if lower.ndim != 1 or lower.shape != upper.shape:
            raise ValueError("Lower and upper corners must be 1D arrays of the same shape.")
        if np.any(upper < lower):
            raise ValueError("Every upper coordinate must be greater than or equal to its lower coordinate.")
        if volume_floor <= 0.0:
            raise ValueError("volume_floor must be strictly positive.")
        self.lower = lower.copy()
        self.upper = upper.copy()
        self.volume_floor = float(volume_floor)
        self._volume = self._calculate_volume()

    @property
    def dimension(self):
        return self.lower.size

    @property
    def volume(self):
        return self._volume

    def _calculate_volume(self):
        sides = self.upper - self.lower
        positive_sides = sides[sides > 0.0]
        if positive_sides.size == 0:
            return self.volume_floor
        return max(float(np.prod(positive_sides)), self.volume_floor)

    def contains(self, points):
        points = np.asarray(points, dtype=float)
        if points.ndim == 1:
            points = points[np.newaxis, :]
        if points.shape[1] != self.dimension:
            raise ValueError("Point dimension does not match the spatial block dimension.")
        return np.all((points >= self.lower) & (points <= self.upper), axis=1)

    def split(self, dimension):
        if dimension < 0 or dimension >= self.dimension:
            raise ValueError("Split dimension is out of range.")
        border = 0.5 * (self.lower[dimension] + self.upper[dimension])
        left_upper = self.upper.copy()
        left_upper[dimension] = border
        right_lower = self.lower.copy()
        right_lower[dimension] = border
        left = SpatialBlock(self.lower, left_upper, self.volume_floor)
        right = SpatialBlock(right_lower, self.upper, self.volume_floor)
        return left, right

    def is_neighbor(self, other, connectivity="corner", tolerance=1e-9):
        if not isinstance(other, SpatialBlock):
            raise TypeError("other must be a SpatialBlock.")
        if connectivity not in {"corner", "face"}:
            raise ValueError("connectivity must be either 'corner' or 'face'.")
        if self.dimension != other.dimension:
            raise ValueError("Spatial blocks must have the same dimension.")
        scale = max(
            float(np.max(self.upper - self.lower)),
            float(np.max(other.upper - other.lower)),
            1.0,
        )
        atol = float(tolerance) * scale
        separated = np.maximum(self.lower, other.lower) > np.minimum(self.upper, other.upper) + atol
        if np.any(separated):
            return False
        touching = (np.abs(self.upper - other.lower) <= atol) | (np.abs(self.lower - other.upper) <= atol)
        overlap = (np.minimum(self.upper, other.upper) - np.maximum(self.lower, other.lower)) > atol
        if connectivity == "corner":
            return bool(np.any(touching))
        return bool(np.any(touching)) and bool(np.all(overlap[~touching]))

    def __repr__(self):
        return f"SpatialBlock(lower={self.lower.tolist()}, upper={self.upper.tolist()})"


class BANGBlock:
    def __init__(self, data, point_indices, region, level, spatial_block):
        self.data = data
        self.point_indices = np.asarray(point_indices, dtype=int)
        self.region = int(region)
        self.level = int(level)
        self.spatial_block = spatial_block
        self.cluster = None
        self.children = []
        self._density = self._calculate_density()

    @property
    def size(self):
        return int(self.point_indices.size)

    @property
    def density(self):
        return self._density

    def _calculate_density(self):
        return float(self.point_indices.size) / self.spatial_block.volume

    def points(self):
        return self.data[self.point_indices]

    def split(self, dimension):
        coordinates = self.data[self.point_indices, dimension]
        border = 0.5 * (
            self.spatial_block.lower[dimension] + self.spatial_block.upper[dimension]
        )
        left_mask = coordinates < border
        left_indices = self.point_indices[left_mask]
        right_indices = self.point_indices[~left_mask]
        left_space, right_space = self.spatial_block.split(dimension)
        left = BANGBlock(self.data, left_indices, self.region * 2, self.level + 1, left_space)
        right = BANGBlock(self.data, right_indices, self.region * 2 + 1, self.level + 1, right_space)
        self.children = [left, right]
        return left, right

    def is_neighbor(self, other, connectivity="corner", tolerance=1e-9):
        return self.spatial_block.is_neighbor(other.spatial_block, connectivity, tolerance)

    def set_cluster(self, cluster_index):
        self.cluster = None if cluster_index is None else int(cluster_index)

    def __len__(self):
        return self.size

    def __repr__(self):
        return (
            f"BANGBlock(region={self.region}, level={self.level}, "
            f"size={self.size}, density={self.density:.6g})"
        )


class BANGDirectory:
    def __init__(
        self,
        data,
        levels,
        density_threshold=0.0,
        amount_threshold=0,
        connectivity="corner",
        volume_floor=1e-12,
    ):
        data = np.asarray(data, dtype=float)
        if data.ndim != 2:
            raise ValueError("data must be a two-dimensional array.")
        if data.shape[0] == 0 or data.shape[1] == 0:
            raise ValueError("data must contain at least one sample and one feature.")
        if int(levels) < 1:
            raise ValueError("levels must be at least 1.")
        if float(density_threshold) < 0.0:
            raise ValueError("density_threshold must be non-negative.")
        if int(amount_threshold) < 0:
            raise ValueError("amount_threshold must be non-negative.")
        if connectivity not in {"corner", "face"}:
            raise ValueError("connectivity must be either 'corner' or 'face'.")
        self.data = np.ascontiguousarray(data)
        self.levels = int(levels)
        self.density_threshold = float(density_threshold)
        self.amount_threshold = int(amount_threshold)
        self.connectivity = connectivity
        self.volume_floor = float(volume_floor)
        self.lower = np.min(self.data, axis=0)
        self.upper = np.max(self.data, axis=0)
        root_space = SpatialBlock(self.lower, self.upper, self.volume_floor)
        self.root = BANGBlock(
            self.data,
            np.arange(self.data.shape[0], dtype=int),
            region=0,
            level=0,
            spatial_block=root_space,
        )
        self.level_blocks = [[self.root]]
        self.leaf_blocks = []
        self._build_directory()
        self.size = int(sum(len(blocks) for blocks in self.level_blocks))

    def _must_stop(self, block):
        if block.size == 0:
            return True
        if block.size <= self.amount_threshold:
            return True
        return block.density <= self.density_threshold

    def _select_split_dimension(self, block, level):
        dimension = block.spatial_block.dimension
        start = (level - 1) % dimension
        for offset in range(dimension):
            candidate = (start + offset) % dimension
            span = block.spatial_block.upper[candidate] - block.spatial_block.lower[candidate]
            if span > np.finfo(float).eps:
                return candidate
        return None

    def _build_directory(self):
        current_level = [self.root]
        for level in range(1, self.levels):
            next_level = []
            for block in current_level:
                if self._must_stop(block):
                    self.leaf_blocks.append(block)
                    continue
                split_dimension = self._select_split_dimension(block, level)
                if split_dimension is None:
                    self.leaf_blocks.append(block)
                    continue
                left, right = block.split(split_dimension)
                next_level.extend((left, right))
            if not next_level:
                current_level = []
                break
            self.level_blocks.append(next_level)
            current_level = next_level
        self.leaf_blocks.extend(current_level)
        self.leaf_blocks.sort(key=lambda block: (block.density, block.region))

    def get_data(self):
        return self.data

    def get_leafs(self):
        return list(self.leaf_blocks)

    def get_level(self, level):
        return list(self.level_blocks[level])

    def get_height(self):
        return len(self.level_blocks)

    def get_root(self):
        return self.root


class BANGClustering:
    def __init__(
        self,
        levels=8,
        density_threshold=0.0,
        amount_threshold=0,
        connectivity="corner",
        volume_floor=1e-12,
    ):
        if int(levels) < 1:
            raise ValueError("levels must be at least 1.")
        if float(density_threshold) < 0.0:
            raise ValueError("density_threshold must be non-negative.")
        if int(amount_threshold) < 0:
            raise ValueError("amount_threshold must be non-negative.")
        if connectivity not in {"corner", "face"}:
            raise ValueError("connectivity must be either 'corner' or 'face'.")
        if float(volume_floor) <= 0.0:
            raise ValueError("volume_floor must be strictly positive.")
        self.levels = int(levels)
        self.density_threshold = float(density_threshold)
        self.amount_threshold = int(amount_threshold)
        self.connectivity = connectivity
        self.volume_floor = float(volume_floor)
        self.directory_ = None
        self.labels_ = None
        self.clusters_ = []
        self.noise_ = np.array([], dtype=int)
        self.cluster_blocks_ = []
        self.dendrogram_ = []
        self.n_features_in_ = None

    def _validate_data(self, X):
        data = np.asarray(X, dtype=float)
        if data.ndim != 2:
            raise ValueError("X must be a two-dimensional array.")
        if data.shape[0] == 0 or data.shape[1] == 0:
            raise ValueError("X must contain at least one sample and one feature.")
        if not np.all(np.isfinite(data)):
            raise ValueError("X must not contain NaN or infinite values.")
        return np.ascontiguousarray(data)

    def fit(self, X, y=None):
        data = self._validate_data(X)
        self.n_features_in_ = data.shape[1]
        self.directory_ = BANGDirectory(
            data,
            levels=self.levels,
            density_threshold=self.density_threshold,
            amount_threshold=self.amount_threshold,
            connectivity=self.connectivity,
            volume_floor=self.volume_floor,
        )
        self._allocate_clusters()
        self._store_results()
        return self

    def _allocate_clusters(self):
        candidates = [
            block
            for block in self.directory_.leaf_blocks
            if block.density > self.density_threshold
            and block.size > self.amount_threshold
        ]
        candidates.sort(key=lambda block: (block.density, block.region), reverse=True)
        adjacency = {index: set() for index in range(len(candidates))}
        for first in range(len(candidates)):
            for second in range(first + 1, len(candidates)):
                if candidates[first].is_neighbor(candidates[second], self.connectivity):
                    adjacency[first].add(second)
                    adjacency[second].add(first)
        assigned = [-1] * len(candidates)
        cluster_blocks = []
        for seed in range(len(candidates)):
            if assigned[seed] != -1:
                continue
            cluster_index = len(cluster_blocks)
            assigned[seed] = cluster_index
            queue = deque([seed])
            members = []
            while queue:
                current = queue.popleft()
                members.append(candidates[current])
                for neighbor in adjacency[current]:
                    if assigned[neighbor] == -1:
                        assigned[neighbor] = cluster_index
                        queue.append(neighbor)
            members.sort(key=lambda block: (block.density, block.region), reverse=True)
            for block in members:
                block.set_cluster(cluster_index)
            cluster_blocks.append(members)
        self.cluster_blocks_ = cluster_blocks
        self.dendrogram_ = [list(blocks) for blocks in cluster_blocks]

    def _store_results(self):
        labels = np.full(self.directory_.data.shape[0], -1, dtype=int)
        for cluster_index, blocks in enumerate(self.cluster_blocks_):
            for block in blocks:
                labels[block.point_indices] = cluster_index
        self.labels_ = labels
        self.clusters_ = [
            np.flatnonzero(labels == cluster_index)
            for cluster_index in range(len(self.cluster_blocks_))
        ]
        self.noise_ = np.flatnonzero(labels == -1)

    def fit_predict(self, X, y=None):
        return self.fit(X, y).labels_

    def get_clusters(self):
        return [cluster.copy() for cluster in self.clusters_]

    def get_noise(self):
        return self.noise_.copy()

    def get_labels(self):
        if self.labels_ is None:
            raise RuntimeError("The model has not been fitted yet.")
        return self.labels_.copy()

    def get_directory(self):
        return self.directory_

    def get_dendrogram(self):
        return [list(blocks) for blocks in self.dendrogram_]


class BANGVisualizer:
    def __init__(
        self,
        figsize=(16.0, 5.0),
        point_size=18.0,
        point_alpha=0.82,
        block_alpha=0.48,
        cmap="YlGnBu",
    ):
        self.figsize = figsize
        self.point_size = float(point_size)
        self.point_alpha = float(point_alpha)
        self.block_alpha = float(block_alpha)
        self.cmap = cmap

    def _resolve_axes(self, n_features, feature_indices):
        if n_features == 1:
            if feature_indices is None:
                feature_indices = (0, 0)
            return 0, None
        if feature_indices is None:
            feature_indices = (0, 1)
        first, second = feature_indices
        if first < 0 or second < 0 or first >= n_features or second >= n_features:
            raise ValueError("feature_indices is out of range.")
        if first == second:
            raise ValueError("feature_indices must contain two different dimensions.")
        return int(first), int(second)

    def _coordinates(self, X, feature_indices):
        X = np.asarray(X, dtype=float)
        if X.ndim != 2:
            raise ValueError("X must be a two-dimensional array.")
        first, second = self._resolve_axes(X.shape[1], feature_indices)
        x = X[:, first]
        y = np.zeros(X.shape[0], dtype=float) if second is None else X[:, second]
        return x, y, first, second

    def _rectangle(self, block, first, second):
        lower = block.spatial_block.lower
        upper = block.spatial_block.upper
        x0 = float(lower[first])
        width = float(upper[first] - lower[first])
        if second is None:
            y0 = -0.5
            height = 1.0
        else:
            y0 = float(lower[second])
            height = float(upper[second] - lower[second])
        return x0, y0, width, height

    def _set_limits(self, axis, directory, first, second):
        data = directory.data
        x = data[:, first]
        x_pad = max(float(np.ptp(x)) * 0.05, 1e-9)
        axis.set_xlim(float(np.min(x)) - x_pad, float(np.max(x)) + x_pad)
        if second is None:
            axis.set_ylim(-0.7, 0.7)
        else:
            y = data[:, second]
            y_pad = max(float(np.ptp(y)) * 0.05, 1e-9)
            axis.set_ylim(float(np.min(y)) - y_pad, float(np.max(y)) + y_pad)

    def _cluster_color(self, cluster_index):
        colormap = plt.get_cmap("tab10")
        return colormap(int(cluster_index) % 10)

    def plot_blocks(self, directory, ax=None, feature_indices=(0, 1), colorbar=True):
        if directory is None:
            raise ValueError("directory must not be None.")
        if ax is None:
            _, ax = plt.subplots(figsize=(7.0, 6.0))
        first, second = self._resolve_axes(directory.data.shape[1], feature_indices)
        x, y, _, _ = self._coordinates(directory.data, feature_indices)
        densities = np.array([block.density for block in directory.leaf_blocks], dtype=float)
        if densities.size == 0:
            raise ValueError("The directory does not contain any block.")
        vmin = float(np.min(densities))
        vmax = float(np.max(densities))
        if vmax <= vmin:
            vmax = vmin + 1.0
        norm = mcolors.Normalize(vmin=vmin, vmax=vmax)
        colormap = plt.get_cmap(self.cmap)
        for block in directory.leaf_blocks:
            x0, y0, width, height = self._rectangle(block, first, second)
            facecolor = colormap(norm(block.density))
            rectangle = patches.Rectangle(
                (x0, y0),
                width,
                height,
                facecolor=facecolor,
                edgecolor="#263238",
                linewidth=0.45,
                alpha=self.block_alpha,
            )
            ax.add_patch(rectangle)
        ax.scatter(x, y, s=4.0, color="#111111", alpha=0.55, linewidths=0.0, zorder=3)
        self._set_limits(ax, directory, first, second)
        ax.set_xlabel(f"Feature {first}")
        ax.set_ylabel("Value" if second is None else f"Feature {second}")
        ax.set_title("BANG blocks")
        ax.grid(False)
        if colorbar:
            scalar_map = plt.cm.ScalarMappable(cmap=colormap, norm=norm)
            scalar_map.set_array(densities)
            plt.colorbar(scalar_map, ax=ax, fraction=0.046, pad=0.04, label="Density")
        return ax

    def plot_clusters(
        self,
        X,
        labels,
        directory=None,
        ax=None,
        feature_indices=(0, 1),
        show_noise=True,
    ):
        X = np.asarray(X, dtype=float)
        labels = np.asarray(labels, dtype=int)
        if X.ndim != 2:
            raise ValueError("X must be a two-dimensional array.")
        if labels.shape[0] != X.shape[0]:
            raise ValueError("labels and X must contain the same number of samples.")
        if ax is None:
            _, ax = plt.subplots(figsize=(7.0, 6.0))
        x, y, first, second = self._coordinates(X, feature_indices)
        for cluster_index in sorted(int(value) for value in np.unique(labels) if value >= 0):
            mask = labels == cluster_index
            ax.scatter(
                x[mask],
                y[mask],
                s=self.point_size,
                color=self._cluster_color(cluster_index),
                alpha=self.point_alpha,
                edgecolors="none",
                label=f"Cluster {cluster_index}",
                zorder=4,
            )
        if show_noise and np.any(labels < 0):
            mask = labels < 0
            ax.scatter(
                x[mask],
                y[mask],
                s=self.point_size * 1.3,
                color="#7a7a7a",
                marker="x",
                linewidths=0.9,
                alpha=0.85,
                label="Noise",
                zorder=5,
            )
        if directory is not None:
            for block in directory.leaf_blocks:
                x0, y0, width, height = self._rectangle(block, first, second)
                if block.cluster is None:
                    edgecolor = "#b0bec5"
                    linewidth = 0.35
                else:
                    edgecolor = self._cluster_color(block.cluster)
                    linewidth = 0.7
                ax.add_patch(
                    patches.Rectangle(
                        (x0, y0),
                        width,
                        height,
                        fill=False,
                        edgecolor=edgecolor,
                        linewidth=linewidth,
                        alpha=0.85,
                        zorder=2,
                    )
                )
            self._set_limits(ax, directory, first, second)
        else:
            x_pad = max(float(np.ptp(x)) * 0.05, 1e-9)
            y_pad = max(float(np.ptp(y)) * 0.05, 1e-9)
            ax.set_xlim(float(np.min(x)) - x_pad, float(np.max(x)) + x_pad)
            ax.set_ylim(float(np.min(y)) - y_pad, float(np.max(y)) + y_pad)
        ax.set_xlabel(f"Feature {first}")
        ax.set_ylabel("Value" if second is None else f"Feature {second}")
        ax.set_title("BANG clusters")
        ax.grid(False)
        if np.any(labels >= 0) or (show_noise and np.any(labels < 0)):
            ax.legend(loc="best", frameon=True, fontsize=8)
        return ax

    def plot_dendrogram(self, dendrogram, ax=None):
        if dendrogram is None:
            raise ValueError("dendrogram must not be None.")
        if ax is None:
            _, ax = plt.subplots(figsize=(8.0, 4.5))
        position = 0
        for cluster_index, blocks in enumerate(dendrogram):
            if len(blocks) == 0:
                continue
            densities = np.array([block.density for block in blocks], dtype=float)
            positions = np.arange(position, position + len(blocks))
            ax.bar(
                positions,
                densities,
                width=0.9,
                color=self._cluster_color(cluster_index),
                alpha=0.85,
                linewidth=0.0,
                label=f"Cluster {cluster_index}",
            )
            position += len(blocks)
        ax.set_xlabel("BANG block")
        ax.set_ylabel("Density")
        ax.set_title("BANG dendrogram")
        ax.set_xticks([])
        ax.grid(axis="y", alpha=0.25)
        if position > 0:
            ax.set_xlim(-0.7, position - 0.3)
        return ax

    def plot_all(
        self,
        X,
        labels,
        directory,
        dendrogram,
        feature_indices=(0, 1),
    ):
        figure, axes = plt.subplots(1, 3, figsize=self.figsize)
        self.plot_blocks(directory, ax=axes[0], feature_indices=feature_indices, colorbar=False)
        self.plot_clusters(
            X,
            labels,
            directory=directory,
            ax=axes[1],
            feature_indices=feature_indices,
        )
        self.plot_dendrogram(dendrogram, ax=axes[2])
        figure.tight_layout()
        return figure


def _make_demo_data(seed=42):
    rng = np.random.default_rng(seed)
    centers = np.array([[0.0, 0.0], [6.5, 0.0], [3.2, 6.5]], dtype=float)
    scales = np.array([[0.55, 0.55], [0.60, 0.48], [0.52, 0.62]], dtype=float)
    sizes = [160, 145, 150]
    clusters = [
        rng.normal(loc=centers[index], scale=scales[index], size=(sizes[index], 2))
        for index in range(3)
    ]
    outliers = []
    while len(outliers) < 16:
        candidate = rng.uniform(low=[-2.0, -2.0], high=[9.0, 9.0])
        distance = np.min(np.linalg.norm(centers - candidate, axis=1))
        if distance > 1.5:
            outliers.append(candidate)
    data = np.vstack(clusters + [np.asarray(outliers, dtype=float)])
    rng.shuffle(data)
    return data


